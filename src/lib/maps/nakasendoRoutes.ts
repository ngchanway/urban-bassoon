const MAX_VIAS = 4

/** Midpoints for live OSRM vias (excludes endpoints; capped to avoid false branches). */
export function hikeViaPoints(route: HikeRoute): { lat: number; lng: number }[] {
  const wps = route.waypoints?.length >= 2 ? route.waypoints : route.coordinates
  if (wps.length < 3) return []
  const mids = wps.slice(1, -1)
  if (mids.length <= MAX_VIAS) return mids.map(([lat, lng]) => ({ lat, lng }))
  const out: { lat: number; lng: number }[] = []
  for (let i = 0; i < MAX_VIAS; i++) {
    const idx = Math.round(((i + 1) * (mids.length + 1)) / (MAX_VIAS + 1)) - 1
    const p = mids[Math.max(0, Math.min(mids.length - 1, idx))]!
    out.push({ lat: p[0], lng: p[1] })
  }
  return out
}

/** True if From/To lie near a curated hike’s endpoints. */
export function matchDemoHikeRoute(
  from: { lat: number; lng: number },
  to: { lat: number; lng: number },
  padDeg = 0.025,
): HikeRoute | null {
  const near = (a: { lat: number; lng: number }, b: [number, number]) =>
    Math.abs(a.lat - b[0]) <= padDeg && Math.abs(a.lng - b[1]) <= padDeg

  for (const route of DEMO_HIKE_ROUTES) {
    const wps = route.waypoints?.length >= 2 ? route.waypoints : route.coordinates
    if (wps.length < 2) continue
    const start = wps[0]!
    const end = wps[wps.length - 1]!
    if ((near(from, start) && near(to, end)) || (near(from, end) && near(to, start))) {
      return route
    }
  }
  return null
}

export function boundsFromCoords(
  coords: [number, number][],
  padDeg = 0.08,
): { south: number; west: number; north: number; east: number } | null {
  if (!coords.length) return null
  let south = coords[0][0]
  let north = coords[0][0]
  let west = coords[0][1]
  let east = coords[0][1]
  for (const [lat, lng] of coords) {
    south = Math.min(south, lat)
    north = Math.max(north, lat)
    west = Math.min(west, lng)
    east = Math.max(east, lng)
  }
  return {
    south: south - padDeg,
    north: north + padDeg,
    west: west - padDeg,
    east: east + padDeg,
  }
}
